class KNN:
    def __init__(self, data: np.ndarray, y: np.ndarray):
        assert len(y) == len(data)
        self.data = data
        self.d = len(self.data[0])
        self.N = len(self.data)
        self.y = y
        self.t = len(y[0])
    
    def get_density(self, x, k):
        assert len(x) == self.d
        radius = np.sort([np.linalg.norm(x - sample) for sample in self.data])[k-1]
        volume = radius * radius * np.pi
        return k / (self.N * volume)
    
    def get_classification(self, x, k):
        assert len(x) == self.d

        neighbors = [np.linalg.norm(x - sample) for sample in self.data]
        indices = list(range(self.N))
        indices.sort(key=lambda i: neighbors[i])

        a = [np.array([self.y[i]]) for i in indices[:k]]

        return np.sum(a, axis=0) / k
        



